-- Run as the database owner, never as the application's runtime role.
BEGIN;
SELECT pg_advisory_xact_lock(42620, 1);

CREATE SCHEMA IF NOT EXISTS cb_identity;
REVOKE ALL ON SCHEMA cb_identity FROM PUBLIC;

CREATE TABLE IF NOT EXISTS cb_identity.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider TEXT NOT NULL,
    issuer TEXT NOT NULL,
    subject TEXT NOT NULL,
    email TEXT,
    email_verified INTEGER CHECK (email_verified IN (0, 1)),
    first_seen_at_utc TEXT NOT NULL,
    last_seen_at_utc TEXT NOT NULL,
    UNIQUE (issuer, subject)
);

CREATE TABLE IF NOT EXISTS cb_identity.legal_acknowledgments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES cb_identity.users(id),
    accepted_at_utc TEXT NOT NULL,
    terms_version TEXT NOT NULL,
    privacy_version TEXT NOT NULL,
    legal_version TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_legal_acks_user_versions
ON cb_identity.legal_acknowledgments
    (user_id, terms_version, privacy_version, legal_version);

REVOKE ALL ON ALL TABLES IN SCHEMA cb_identity FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA cb_identity FROM PUBLIC;
COMMIT;

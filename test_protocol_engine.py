def test_universe_filtering_and_cap_ties_do_not_mutate_inputs():
    import protocol_engine as engine

    constituents = pd.DataFrame({
        "Symbol": ["B.B", "OIL", "GOOG", "AAA", "MISSING"],
        "GICS Sector": ["Technology", "Energy", "Technology", "Health Care", "Industrials"],
    })
    original = constituents.copy(deep=True)
    candidates, sectors = engine.prepare_universe(constituents, {"GOOG"})
    assert candidates == ["B-B", "AAA", "MISSING"]
    assert sectors == {"B-B": "Technology", "GOOG": "Technology",
                       "AAA": "Health Care", "MISSING": "Industrials"}
    caps = {"B-B": 100, "AAA": 100, "MISSING": 50}
    assert engine.select_universe(candidates, caps, 2) == ["B-B", "AAA", "SPY"]
    assert engine.select_universe(candidates, caps, 10) == ["B-B", "AAA", "MISSING", "SPY"]
    # Unknown market caps are explicitly assigned zero and ranked last.
    del caps["MISSING"]
    assert engine.select_universe(candidates, caps, 10) == ["B-B", "AAA", "MISSING", "SPY"]
    assert candidates == ["B-B", "AAA", "MISSING"]
    assert caps == {"B-B": 100, "AAA": 100}
    pd.testing.assert_frame_equal(constituents, original, check_exact=True)


def test_factor_analysis_listwise_dropna_and_validation_order(monkeypatch):
    import protocol_engine as engine

    returns = pd.DataFrame({
        "AAA": [0.01, np.nan, 0.03, 0.04],
        "BBB": [0.02, 0.03, np.nan, 0.05],
    })
    original = returns.copy(deep=True)
    seen = []

    def validate(matrix):
        seen.append(matrix.copy())
        return matrix

    class Analyzer:
        def __init__(self, n_factors, rotation, method):
            assert (n_factors, rotation, method) == (2, "varimax", "minres")

        def fit(self, matrix):
            seen.append(matrix.copy())
            self.loadings_ = np.array([[0.3, 0.3], [-0.8, 0.2]])

    monkeypatch.setattr(engine, "validate_returns_matrix", validate)
    monkeypatch.setattr(engine, "FactorAnalyzer", Analyzer)
    tickers, loadings, maximum, dominant = engine.fit_factors(returns, ["AAA", "BBB"], 8)
    assert tickers == ["AAA", "BBB"]
    assert len(seen) == 3
    for matrix in seen:
        pd.testing.assert_frame_equal(matrix, returns.loc[[0, 3]], check_exact=True)
    assert maximum.tolist() == [0.3, 0.8]
    assert dominant.tolist() == ["Factor_1", "Factor_1"]
    assert loadings.columns.tolist() == ["Factor_1", "Factor_2"]
    pd.testing.assert_frame_equal(returns, original, check_exact=True)



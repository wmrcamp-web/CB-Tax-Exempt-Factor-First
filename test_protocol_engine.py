def test_shadow_priority_factor_cap_uniqueness_and_equal_weights():
    metrics, loadings, headers = selection_inputs([
        ("SHADOW_LOW_BETA", 0.01, 0.1, 0.3, 0.1),
        ("SHADOW_MID_BETA", 0.02, 0.2, 0.3, 0.1),
        ("SHADOW_HIGH_BETA", 0.03, 0.3, 0.3, 0.1),
        ("SHADOW_CAPPED", 0.9, 0.4, 0.3, 0.1),
        ("NON_SHADOW_CAPPED", 1.0, 0.05, 0.95, 0.1),
        ("MULTI_FACTOR", 0.5, 0.8, 0.8, 0.9),
        ("FACTOR_TWO", 0.3, 0.7, 0.1, 0.7),
        ("FALLBACK", 0.2, 0.6, 0.7, 0.8),
    ])
    shadow_list = [
        "SHADOW_LOW_BETA", "SHADOW_LOW_BETA", "SHADOW_MID_BETA",
        "SHADOW_HIGH_BETA", "SHADOW_CAPPED",
    ]

    portfolio = assemble_selection(metrics, loadings, headers, 8, shadow_list)

    assert portfolio.index.tolist() == [
        "SHADOW_LOW_BETA", "SHADOW_MID_BETA", "SHADOW_HIGH_BETA",
        "MULTI_FACTOR", "FACTOR_TWO", "FALLBACK",
    ]
    assert portfolio.index.is_unique
    assert portfolio["Dominant_Factor"].value_counts().to_dict() == {
        "Factor_1": 3, "Factor_2": 3,
    }
    assert portfolio["Weight (%)"].tolist() == [round(100 / 6, 2)] * 6
    assert portfolio["In_Shadow_List"].tolist() == [True] * 3 + [False] * 3
    assert assemble_selection(metrics, loadings, headers, 2, shadow_list).index.tolist() == [
        "SHADOW_LOW_BETA", "SHADOW_MID_BETA",
    ]


def test_fallback_prefers_return_and_requires_an_actual_qualifying_loading():
    metrics, loadings, headers = selection_inputs([
        ("FIRST", 0.4, 1.0, 0.6, 0.1),
        ("HIGH_RETURN", 0.3, 0.9, -0.6, 0.1),
        ("LOW_RETURN", 0.2, 0.1, 0.95, 0.1),
        ("UNQUALIFIED", 0.9, 0.01, 0.589999, -0.589999),
        ("NO_LOADINGS", 1.0, 0.01, 0.9, 0.1),
    ])
    # A stale maximum or absent loading row cannot grant fallback eligibility.
    metrics.loc["UNQUALIFIED", "Max_Factor_Loading"] = 0.95
    loadings = loadings.drop(index="NO_LOADINGS")

    assert assemble_selection(metrics, loadings, headers, 2).index.tolist() == [
        "FIRST", "HIGH_RETURN",
    ]
    assert assemble_selection(metrics, loadings, headers, 5).index.tolist() == [
        "FIRST", "HIGH_RETURN", "LOW_RETURN",
    ]



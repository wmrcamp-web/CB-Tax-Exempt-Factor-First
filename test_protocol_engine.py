def output_fingerprint(result):
    benchmark, *frames, headers = result
    payload = [float(benchmark).hex(), headers]
    for frame in frames:
        payload.append({
            "csv": frame.to_csv(),
            "index_name": frame.index.name,
            "columns_name": frame.columns.name,
        })
    return hashlib.sha256(json.dumps(payload, ensure_ascii=True).encode()).hexdigest()


def install_characterization_inputs(monkeypatch, mod, case):
    periods = 120
    weeks = np.arange(periods - 1)
    spy_returns = np.where(
        weeks % 2 == 0, 0.018 + 0.002 * np.sin(weeks),
        -0.012 - 0.004 * (weeks % 7) / 7,
    )
    prices = {"SPY": 100 * np.cumprod(1 + np.r_[0.0, spy_returns])}
    for i, ticker in enumerate(TICKERS):
        beta = 0.8 if i < 2 else 0.8 + 0.05 * i
        prices[ticker] = 100 * np.cumprod(1 + np.r_[0.0, beta * spy_returns])
    closes = pd.DataFrame(prices, index=pd.date_range("2023-09-15", periods=periods, freq="W-FRI"))
    if case == "missing":
        # The first trailing close must be filled from OUTSIDE the 53-row window.
        closes.loc[closes.index[-53], "Z-Z"] = np.nan
        closes.loc[closes.index[-20:-17], "AAA"] = np.nan
        closes.loc[closes.index[:-30], "III"] = np.nan

    symbols = ["Z.Z", "AAA", "GOOG", "OIL", "MSTR"] + TICKERS[2:]
    sectors = ["Technology", "Health Care", "Technology", "Energy", "Financials",
               "Health Care", "Technology", "Financials", "Financials",
               "Industrials", "Technology", "Health Care", "Industrials"]
    constituents = pd.DataFrame({"Symbol": symbols, "GICS Sector": sectors})
    caps = {t: (20 - i // 2) * 1e9 for i, t in enumerate(TICKERS)}
    captured = {"errors": [], "spinners": [], "fits": [], "validations": []}

    @contextmanager
    def spinner(message):
        captured["spinners"].append(message)
        yield

    def fetch_caps(candidates, as_of_date):
        captured["candidates"] = candidates
        captured["market_caps_date"] = as_of_date
        return sorted(candidates, key=lambda t: caps.get(t, 0), reverse=True), caps

    def get_market_caps(candidates, as_of_date):
        _, market_caps = fetch_caps(candidates, as_of_date)
        return market_caps

    def download(tickers, start_date, end_date):
        captured["download"] = (
            tickers,
            {
                "start": start_date, "end": end_date,
                "interval": "1wk", "progress": False,
            },
        )
        return closes[tickers]

    class Analyzer:
        def __init__(self, n_factors, rotation, method):
            captured["analyzer"] = (n_factors, rotation, method)
            self.n_factors = n_factors

        def fit(self, matrix):
            captured["fits"].append(matrix.copy())
            if case == "fit_error":
                raise ValueError("synthetic fit failure")
            self.loadings_ = LOADINGS[[TICKERS.index(t) for t in matrix.columns], :self.n_factors]

    def validate(matrix):
        captured["validations"].append(matrix.copy())
        if case == "validation_error":
            raise ValueError("synthetic validation failure")
        return matrix

    def get_constituents(as_of_date):
        captured["constituents_date"] = as_of_date
        return constituents

    monkeypatch.setattr(mod.DEFAULT_PROVIDER, "get_constituents", get_constituents)
    monkeypatch.setattr(mod.DEFAULT_PROVIDER, "get_market_caps", get_market_caps)
    monkeypatch.setattr(mod.DEFAULT_PROVIDER, "get_weekly_closes", download)
    monkeypatch.setattr("protocol_engine.FactorAnalyzer", Analyzer)
    monkeypatch.setattr("protocol_engine.validate_returns_matrix", validate)
    monkeypatch.setattr(mod.st, "error", captured["errors"].append)
    monkeypatch.setattr(mod.st, "spinner", spinner)
    monkeypatch.setattr(mod, "universe_size", 10)
    monkeypatch.setattr(mod, "n_factors", 4)
    monkeypatch.setattr(mod, "shadow_cutoff", 0.4)
    monkeypatch.setattr(mod, "target_portfolio_size", 8)
    gate = None
    if case == "gate_boundary":
        gate = closes["BBB"].iloc[-1] / closes["BBB"].iloc[-53] - 1.0
    elif case == "no_survivors":
        gate = 10.0
    elif case == "zero_target":
        monkeypatch.setattr(mod, "target_portfolio_size", 0)
    elif case == "factor_cap":
        monkeypatch.setattr(mod, "universe_size", 2)
    elif case == "zero_factors":
        monkeypatch.setattr(mod, "n_factors", 0)
    elif case == "rounded_weights":
        monkeypatch.setattr(mod, "target_portfolio_size", 3)
    return gate, captured, closes


@pytest.mark.parametrize("mod_key", ["app", "cb_taxable_portfolio_app"])
@pytest.mark.parametrize("case", BASELINE)
def test_original_pipeline_outputs(app_modules, monkeypatch, mod_key, case):
    mod = app_modules[mod_key]
    gate, captured, closes = install_characterization_inputs(monkeypatch, mod, case)
    result = mod.run_pipeline(datetime.date(2025, 12, 31), gate)

    assert isinstance(result, tuple) and len(result) == 6
    assert output_fingerprint(result) == BASELINE[case]
    assert captured["candidates"] == TICKERS
    assert captured["constituents_date"] == datetime.date(2025, 12, 31)
    assert captured["market_caps_date"] == datetime.date(2025, 12, 31)
    requested, options = captured["download"]
    assert requested == (TICKERS[:2] if case == "factor_cap" else TICKERS) + ["SPY"]
    assert options == {
        "start": datetime.date(2025, 12, 31) - datetime.timedelta(days=742),
        "end": datetime.date(2025, 12, 31), "interval": "1wk", "progress": False,
    }
    if case in {"no_survivors", "zero_factors", "validation_error", "fit_error"}:
        errors = {
            "no_survivors": "No factor-eligible tickers passed the performance gate!",
            "zero_factors": "Not enough tickers for factor analysis to extract any factors.",
            "validation_error": "Data validation failed prior to factor analysis: synthetic validation failure",
            "fit_error": "Factor analysis failed: synthetic fit failure. This might be due to insufficient data or correlation issues.",
        }
        assert captured["errors"] == [errors[case]]
        assert all(frame.empty for frame in result[1:4])
        assert result[5] == []
    else:
        assert captured["errors"] == []
        assert len(captured["validations"]) == 2
        matrix = captured["fits"][0]
        expected = closes[requested].ffill().iloc[-53:].dropna(axis=1)
        expected = expected.pct_change().dropna(how="all")[matrix.columns].dropna()
        pd.testing.assert_frame_equal(matrix, expected, check_exact=True)
        if case == "gate_boundary":
            assert "BBB" in result[4].index
        if case == "normal":
            assert result[5] == [
                "Factor_1\n(Technology)", "Factor_2\n(Financials)",
                "Factor_3\n(Industrials)", "Factor_4\n(Mixed)",
            ]
            assert result[3].index.tolist() == ["Z-Z", "AAA", "CCC", "HHH", "III", "EEE", "DDD"]
            assert result[3]["Weight (%)"].tolist() == [round(100 / 7, 2)] * 7
            assert result[3]["Dominant_Factor"].value_counts().max() == 3
        if case == "rounded_weights":
            assert result[3]["Weight (%)"].tolist() == [33.33] * 3
    expected_spinners = [
        "Fetching S&P 500 constituents ending 2025-12-31...",
        "Sorting universe by actual Market Capitalization...",
        "Downloading historical price data...",
        "Executing Phase 2: 8-Factor Varimax Orthogonality & Factor Loadings (full universe)...",
    ]
    if case not in {"zero_factors", "validation_error", "fit_error"}:
        expected_spinners.append("Executing Phase 3: Performance Gate (T12M)...")
    if not captured["errors"]:
        expected_spinners += [
            "Executing Phase 4: Quantitative Scoring (Downside Beta) & Shadow List Identification...",
            "Analyzing Dominant Sectors per Factor...",
            "Executing Phase 5: Selection & Portfolio Assembly...",
        ]
    assert captured["spinners"] == expected_spinners

    # Infer text dtypes just as the original constructors do, including pandas'
    # default string dtype on newer versions; do not freeze a library version.
    text_dtype = pd.Series(["Ticker"]).dtype
    for frame in result[1:5]:
        if not frame.empty:
            assert frame.index.dtype == text_dtype
            for col, dtype in frame.dtypes.items():
                expected_dtype = (
                    text_dtype if col in {"Dominant_Factor", "Sector"}
                    else np.dtype(bool) if col == "In_Shadow_List"
                    else np.dtype(float)
                )
                assert dtype == expected_dtype



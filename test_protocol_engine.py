def selection_inputs(rows):
    """Rows contain ticker, trailing return, downside beta, and factor loadings."""
    headers = ["Factor_1", "Factor_2"]
    metrics = pd.DataFrame(
        [row[:3] for row in rows],
        columns=["Ticker", "T12M_Return", "Downside_Beta"],
    ).set_index("Ticker")
    loadings = pd.DataFrame([row[3:] for row in rows], index=metrics.index, columns=headers)
    metrics["Max_Factor_Loading"] = loadings.abs().max(axis=1)
    metrics["Dominant_Factor"] = loadings.abs().idxmax(axis=1)
    metrics["Sector"] = "Technology"
    return metrics, loadings, headers


def assemble_selection(metrics, loadings, headers, target, shadow_list=()):
    import protocol_engine as engine

    return engine.assemble_portfolio(
        0.1, metrics, loadings, pd.DataFrame(), headers, shadow_list, target
    )[3]


def test_non_shadow_return_beats_stronger_loading_and_lower_beta():
    metrics, loadings, headers = selection_inputs([
        ("STRONG_LOADING", 0.1, 0.2, 0.95, 0.1),
        ("LOW_BETA", 0.2, 0.1, 0.8, 0.1),
        ("HIGH_RETURN", 0.3, 0.9, 0.6, 0.1),
    ])

    portfolio = assemble_selection(metrics, loadings, headers, 1)

    assert portfolio.index.tolist() == ["HIGH_RETURN"]
    assert portfolio["Weight (%)"].tolist() == [100.0]
    assert portfolio.columns.tolist() == metrics.columns.tolist() + ["Weight (%)", "In_Shadow_List"]


